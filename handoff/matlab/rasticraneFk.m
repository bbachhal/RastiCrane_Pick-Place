function point_mm = rasticraneFk(angles_deg,model)
% angles=[shoulder forearmABS yaw]. Parallelogram, not serial elbow angle.
radial_mm=model.shoulderForward_mm+model.upperArm_mm*cosd(angles_deg(1))+ ...
    model.forearm_mm*cosd(angles_deg(2))+model.toolForward_mm;
yaw_deg=angles_deg(3);
point_mm=[radial_mm*cosd(yaw_deg)-model.toolSideways_mm*sind(yaw_deg), ...
    radial_mm*sind(yaw_deg)+model.toolSideways_mm*cosd(yaw_deg), ...
    model.shoulderHeight_mm+model.upperArm_mm*sind(angles_deg(1))+ ...
    model.forearm_mm*sind(angles_deg(2))+model.toolVertical_mm];
end
